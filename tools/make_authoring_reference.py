#!/usr/bin/env python3
"""Generate schemas and operation documentation from the live descriptors."""
import json
from pathlib import Path
from authoring_contract import BATCH_SCHEMA,OPERATIONS
from authoring_scenarios import SCHEMA,SUITE_SCHEMA
from authoring_protection import RULE_SCHEMA

ROOT=Path(__file__).resolve().parents[1]


def main():
    from construction_library import schema as construction_schema
    from campaign_source import schema as source_schema
    from campaign_limits import schema as capacity_schema
    from campaign_recipe import SCHEMA as recipe_schema
    for name,schema in [('authoring-batch-v1',BATCH_SCHEMA),('authoring-scenario-v1',SCHEMA),('authoring-suite-v1',SUITE_SCHEMA),('authoring-protection-v1',RULE_SCHEMA),
                        ('construction-library-v1',construction_schema()),('campaign-source-v1',source_schema()),('adventure-v3',capacity_schema()),('greybank-recipe-v1',recipe_schema)]:
        value=dict(schema,**{'$schema':'https://json-schema.org/draft/2020-12/schema'})
        (ROOT/'schemas'/f'{name}.schema.json').write_text(json.dumps(value,indent=2)+'\n')
    lines=['# Authoring command reference','',
        'Generated by `python3 tools/make_authoring_reference.py` from the same',
        'descriptors used by the CLI. API version 1. See [the author guide](AI_AUTHORING_GUIDE.md)',
        'for revisions, batches, coordinates, examples and validation boundaries.','',
        'Fields marked `*` are required. The C validator checks complete candidate',
        'projects; an operation schema alone does not prove gameplay legality.','']
    for name,descriptor in OPERATIONS.items():
        lines.extend(['## '+name,'',descriptor['description'],'',
            'Write scope: '+', '.join('`'+s+'`' for s in descriptor['writes'])+'.','',
            '| Field | Structural constraint |','| --- | --- |'])
        schema=descriptor['schema']
        for key,value in schema['properties'].items():
            if key=='op':continue
            lines.append('| `'+key+'`'+(' *' if key in schema['required'] else '')+' | `'+json.dumps(value,separators=(',',':')).replace('|','\\|')+'` |')
        lines.extend(['','```json',json.dumps(descriptor['example'],indent=2),'```',''])
    (ROOT/'docs/AUTHORING_COMMANDS.md').write_text('\n'.join(lines))


if __name__=='__main__':main()
