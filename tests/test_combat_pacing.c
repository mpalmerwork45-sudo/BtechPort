static unsigned checks, case_number;
#define CHECK(x) do { ++checks;if (!(x)) { fprintf(stderr,"%s:%d case %u: %s\n",__FILE__,__LINE__,case_number,#x);exit(1); } } while (0)

/* Check held waits through the real save codec and audio/game tick. Waiting
   must survive a restart without changing the next event or its PCM. */
static void step(BtpState *s,const BtpResources *r,BtpAction action)
{
    uint8_t before[BTP_STATE_BYTES],after[BTP_STATE_BYTES];BtpState copy;
    int16_t a[BTP_AUDIO_TICK_SAMPLES],b[BTP_AUDIO_TICK_SAMPLES];
    btp_state_encode(s,before);
    CHECK(btp_state_decode(before,sizeof before,&r->map,&r->training,&copy));
    btp_game_tick_audio(s,r,action,a);btp_game_tick_audio(&copy,r,action,b);
    btp_state_encode(s,before);btp_state_encode(&copy,after);
    CHECK(!memcmp(before,after,sizeof before) && !memcmp(a,b,sizeof a));
}

static void start_case(BtpState *s,const BtpState *base,const BtpResources *r,
    unsigned graphics,unsigned speed,unsigned moving,unsigned orders)
{
    *s=*base;s->menu.sound=0;s->menu.speed=(uint8_t)speed;
    s->audio=(BtpAudioState){0};s->effects=(BtpEffectsState){0};
    BtpCombatState *c=&s->combat;c->phase=BTP_COMBAT_MENU;c->selected=9;
    c->graphics=(uint8_t)graphics;c->movement=(uint8_t)(moving ? 0 : 255);
    c->goal_active=(uint8_t)moving;c->goal_x=88;c->goal_y=85;
    memset(s->mech_skills,0,sizeof s->mech_skills);
    memcpy(c->unit[0].record,r->combat.loans[0],125);
    memcpy(c->unit[1].record,r->combat.loans[2],125);
    for (unsigned i=0;i<2;++i) {
        c->unit[i].x=(uint8_t)(i ? 90 : 84);c->unit[i].y=85;
        c->unit[i].direction=c->plan_direction[i]=c->fallback[i]=(uint8_t)(i ? 6 : 2);
    }
    s->x_half=84;s->y_half=87;
    memset(c->orders,255,sizeof c->orders);
    for (unsigned i=0;i<orders;++i) c->orders[i]=12;
    s->npc.rng[0]=64;s->npc.rng[1]=226;s->npc.rng[2]=1; /* 123456, original fixture seed. */
    step(s,r,BTP_ACCEPT);CHECK(c->phase==BTP_COMBAT_ROUND && !c->delay);
}

static void waves(const BtpState *base,const BtpResources *r,const char *path)
{
    FILE *file=fopen(path,"r");CHECK(file);char line[256];
    BtpCombatUnit results[2][4][2]={0};uint8_t seeds[2][4][3]={0};
    while (fgets(line,sizeof line,file)) {
        if (line[0]=='#') continue;
        unsigned graphics,speed,moving,orders,steps,shots,pauses,keys,retraces,poses,x,y;
        CHECK(sscanf(line,"%u %u %u %u | %u %u %u %u %u %u %u %u",&graphics,&speed,&moving,&orders,
            &steps,&shots,&pauses,&keys,&retraces,&poses,&x,&y)==12);
        ++case_number;CHECK(graphics<2 && speed<6 && moving<2 && orders<3);
        BtpState s;start_case(&s,base,r,graphics,speed,moving,orders);
        /* Local, controlled prerequisites for bounded SDL pacing checks.
           They are regenerated by this test and never replace player saves. */
        BtpError error;
        if (graphics && speed==2 && moving && !orders)
            CHECK(btp_save_write("work/combat-pacing-move.btp",&s,r,&error));
        if (!graphics && speed==5 && moving && orders==1)
            CHECK(btp_save_write("work/combat-pacing-key.btp",&s,r,&error));
        unsigned ticks=0,advances=0,completed=0,holds=0,wait_ticks=0;
        while (s.combat.phase==BTP_COMBAT_ROUND && ticks++<1024) {
            unsigned old_step=s.combat.step,count=s.effects.count,delay=s.combat.delay;
            if (speed==5 && delay) {
                BtpBattleText shown=s.effects.shown;
                for (unsigned i=0;i<3;++i) {
                    step(&s,r,BTP_IDLE);
                    CHECK(s.combat.delay==delay && s.combat.step==old_step && s.effects.count==count);
                    CHECK(!memcmp(&s.effects.shown,&shown,sizeof shown));
                }
                step(&s,r,BTP_ACCEPT);++holds;
                CHECK(!s.combat.delay && s.combat.step==old_step && s.effects.count==count);
                continue;
            }
            step(&s,r,BTP_IDLE);
            if (delay) {
                ++wait_ticks;CHECK(s.combat.delay==delay-1 && s.combat.step==old_step && s.effects.count==count);
            }
            if (s.combat.step!=old_step) {
                ++advances;CHECK(s.combat.step==old_step+1 && !delay);
            }
            if (s.effects.count<count) {
                ++completed;CHECK(s.effects.count+1u==count && s.effects.shown.active);
                CHECK(s.combat.delay==(speed==5 ? 1u : btp_combat_delay_ticks(speed)));
            }
            if (!graphics && count && !delay) CHECK(s.effects.count+1u==count);
        }
        CHECK(ticks<1024 && s.combat.phase==BTP_COMBAT_MENU);
        CHECK(advances==steps && completed==shots && completed==pauses && holds==keys);
        CHECK(s.combat.unit[0].x==x && s.combat.unit[0].y==y);
        CHECK(graphics || !poses);
        if (speed<5) {
            CHECK(wait_ticks==completed*btp_combat_delay_ticks(speed));
            /* The completed report is visible for one tick before its idle
               countdown. Each attack's rounded pause is within one 32ms tick. */
            unsigned expected=speed ? (retraces*100u+223u)/224u : 0;
            unsigned actual=speed ? wait_ticks+completed : 0;
            CHECK(actual>=expected && actual<=expected+completed);
        }
        if (!orders) CHECK(ticks==12); /* All six speeds, including key-wait mode. */
        if (!graphics && speed<5) CHECK(ticks==12+completed+wait_ticks);
        unsigned scenario=moving ? 1u+orders : 0u;
        if (!speed) {
            memcpy(results[graphics][scenario],s.combat.unit,sizeof results[0][0]);
            memcpy(seeds[graphics][scenario],s.npc.rng,3);
        } else {
            CHECK(!memcmp(results[graphics][scenario],s.combat.unit,sizeof results[0][0]));
            CHECK(!memcmp(seeds[graphics][scenario],s.npc.rng,3));
        }
    }
    fclose(file);CHECK(case_number==48);
}

static void queued_reports(const BtpState *base,const BtpResources *r)
{
    for (unsigned speed=0;speed<6;++speed) {
        BtpState s;start_case(&s,base,r,0,speed,0,0);
        s.combat.step=11;s.combat.shot=(BtpShot){.hit=1};
        btp_effects_shot(&s,0,1,17);btp_effects_shot(&s,1,0,9);btp_effects_shot(&s,0,1,6);
        for (unsigned remaining=3;remaining;--remaining) {
            CHECK(s.effects.count==remaining && !s.combat.delay);
            step(&s,r,BTP_IDLE);CHECK(s.effects.count==remaining-1 && s.combat.step==11);
            BtpBattleText shown=s.effects.shown;
            if (speed==5) {
                step(&s,r,BTP_IDLE);CHECK(s.combat.delay && s.effects.count==remaining-1);
                step(&s,r,BTP_ACCEPT);
            } else while (s.combat.delay) {
                step(&s,r,BTP_IDLE);
                CHECK(s.effects.count==remaining-1 && s.combat.step==11);
                CHECK(!memcmp(&shown,&s.effects.shown,sizeof shown));
            }
        }
        step(&s,r,BTP_IDLE);CHECK(s.combat.phase==BTP_COMBAT_MENU);
    }
    /* A saved key wait acknowledges Space while preserving the assigned
       computer unit; the remaining movement drains before the command menu. */
    BtpState s;start_case(&s,base,r,0,5,0,1);
    while (!s.combat.delay) step(&s,r,BTP_IDLE);
    s.combat.automatic=1;s.combat.auto_run=1;
    step(&s,r,BTP_OPEN_MENU);CHECK(!s.combat.delay && s.combat.paused && !s.combat.auto_run && s.combat.automatic==1);
    for (unsigned i=0;s.combat.phase==BTP_COMBAT_ROUND && i<32;++i) step(&s,r,BTP_IDLE);
    CHECK(s.combat.phase==BTP_COMBAT_MENU && s.combat.paused && s.combat.automatic==1);
}

int main(int argc,char **argv)
{
    if (argc!=6) return 2;
    BtpResources *r=calloc(1,sizeof *r);BtpError error;CHECK(r);
    CHECK(btp_resources_load(argv[1],r,&error));CHECK(btp_dialogue_load(argv[2],&r->dialogue,&error));
    CHECK(btp_combat_data_load(argv[3],&r->combat,&error));
    BtpState base;btp_start(&base);btp_npc_init(&base,&r->map);
    FILE *file=fopen(argv[4],"r");CHECK(file);char line[40];
    while (base.combat.phase!=BTP_COMBAT_MENU && fgets(line,sizeof line,file)) {
        line[strcspn(line,"\r\n")]=0;BtpAction action;CHECK(btp_action_parse(line,&action));
        btp_game_tick(&base,r,action);
    }
    fclose(file);CHECK(base.combat.phase==BTP_COMBAT_MENU);
    waves(&base,r,argv[5]);queued_reports(&base,r);
    free(r);printf("PASS: %u combat pacing assertions, 48 original waves, queued reports and save/audio continuations\n",checks);
    return 0;
}
